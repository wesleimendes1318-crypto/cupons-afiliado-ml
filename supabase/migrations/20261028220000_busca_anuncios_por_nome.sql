-- BUSCA POR NOME NOS ANÚNCIOS (28/10, Weslei: "a ia de busca deve ser muito
-- assertiva, no modelo, versões tudo"). O Nike TC 7900 não tem produto no
-- catálogo oficial (a API devolve Winflo e Downshifter), só anúncios avulsos,
-- que a API não lista (/sites/MLB/search responde 403). Quando o catálogo não
-- tem a marca e o modelo pedidos, o site pede aqui e a extensão faz a mesma
-- busca que uma pessoa faria, devolvendo só os anúncios com a marca e o
-- modelo no título. Nada é gravado sobre quem pediu.

create table if not exists public.buscas_anuncios (
  id bigint generated by default as identity primary key,
  chave text not null default md5(random()::text || clock_timestamp()::text),
  termo text not null,
  marca text,
  modelo text,
  status text not null default 'pendente',
  resultado jsonb,
  erro text,
  criado_em timestamptz not null default now(),
  iniciado_em timestamptz,
  pronto_em timestamptz
);
create index if not exists buscas_anuncios_termo on public.buscas_anuncios (lower(termo), criado_em desc);
alter table public.buscas_anuncios enable row level security;

-- Site (servidor e navegador): pede a busca. Mesmo termo pronto há menos de
-- 6 h ou em andamento há menos de 5 min volta o mesmo pedido.
create or replace function public.pedir_busca_anuncios(p_termo text, p_marca text, p_modelo text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_termo text := left(regexp_replace(trim(coalesce(p_termo, '')), '\s+', ' ', 'g'), 120);
  v_marca text := nullif(left(trim(coalesce(p_marca, '')), 40), '');
  v_modelo text := nullif(left(trim(coalesce(p_modelo, '')), 40), '');
  r record;
begin
  if length(v_termo) < 3 or (v_marca is null and v_modelo is null) then
    return jsonb_build_object('ok', false, 'motivo', 'termo');
  end if;
  if public.extensao_pausada() then
    return jsonb_build_object('ok', false, 'motivo', 'pausada');
  end if;
  select id, chave, status into r from public.buscas_anuncios
   where lower(termo) = lower(v_termo)
     and ((status = 'pronto' and criado_em > now() - interval '6 hours')
          or (status in ('pendente', 'processando') and criado_em > now() - interval '5 minutes'))
   order by id desc limit 1;
  if found then
    return jsonb_build_object('ok', true, 'id', r.id, 'chave', r.chave, 'estado', r.status);
  end if;
  if (select count(*) from public.buscas_anuncios where criado_em > now() - interval '10 minutes') >= 30 then
    return jsonb_build_object('ok', false, 'motivo', 'limite');
  end if;
  insert into public.buscas_anuncios (termo, marca, modelo)
  values (v_termo, v_marca, v_modelo)
  returning id, chave, status into r;
  return jsonb_build_object('ok', true, 'id', r.id, 'chave', r.chave, 'estado', r.status);
end
$$;
revoke all on function public.pedir_busca_anuncios(text, text, text) from public;
grant execute on function public.pedir_busca_anuncios(text, text, text) to anon, authenticated;

-- Site: acompanha o pedido (só com a chave).
create or replace function public.ver_busca_anuncios(p_id bigint, p_chave text)
returns jsonb
language sql
security definer
set search_path = public
as $$
  select jsonb_build_object('estado', b.status, 'resultado', b.resultado, 'criado_em', b.criado_em)
    from public.buscas_anuncios b
   where b.id = p_id and b.chave = p_chave;
$$;
revoke all on function public.ver_busca_anuncios(bigint, text) from public;
grant execute on function public.ver_busca_anuncios(bigint, text) to anon, authenticated;

-- Extensão: até 2 pedidos abertos (travado há 3 min volta).
create or replace function public.buscas_anuncios_pendentes(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v jsonb;
begin
  if p_token is null or p_token <> (select valor from public.sinc_config where chave = 'token') then
    raise exception 'token invalido';
  end if;
  if public.extensao_pausada() then return '[]'::jsonb; end if;
  with escolhidos as (
    select b.id from public.buscas_anuncios b
     where b.criado_em > now() - interval '10 minutes'
       and (b.status = 'pendente'
            or (b.status = 'processando' and b.iniciado_em < now() - interval '3 minutes'))
     order by b.criado_em
     limit 2
     for update skip locked
  ), marcados as (
    update public.buscas_anuncios b
       set status = 'processando', iniciado_em = now()
      from escolhidos e
     where b.id = e.id
    returning b.id, b.termo, b.marca, b.modelo
  )
  select coalesce(jsonb_agg(to_jsonb(m) order by m.id), '[]'::jsonb) into v from marcados m;
  return v;
end
$$;
revoke all on function public.buscas_anuncios_pendentes(text) from public;
grant execute on function public.buscas_anuncios_pendentes(text) to anon, authenticated;

-- Extensão: resultado. Só anúncio do Mercado Livre (MLB...) entra; a tela
-- confere de novo marca e modelo.
create or replace function public.gravar_busca_anuncios(p_token text, p_id bigint, p_resultado jsonb, p_erro text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_token is null or p_token <> (select valor from public.sinc_config where chave = 'token') then
    raise exception 'token invalido';
  end if;
  update public.buscas_anuncios
     set status = case when p_erro is null then 'pronto' else 'falhou' end,
         resultado = case when jsonb_typeof(p_resultado) = 'object' then p_resultado else null end,
         erro = left(p_erro, 300),
         pronto_em = now()
   where id = p_id;
end
$$;
revoke all on function public.gravar_busca_anuncios(text, bigint, jsonb, text) from public;
grant execute on function public.gravar_busca_anuncios(text, bigint, jsonb, text) to anon, authenticated;
